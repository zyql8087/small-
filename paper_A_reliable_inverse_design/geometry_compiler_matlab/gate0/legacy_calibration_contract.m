function contract = legacy_calibration_contract()
%LEGACY_CALIBRATION_CONTRACT Versioned constants for the immutable M04 freeze.

    baseDirectory = fileparts(fileparts(mfilename('fullpath')));
    config = load_compiler_config(fullfile(baseDirectory, 'configs', ...
        'compiler_config.example.json'));
    definition = jsondecode(fileread(config.descriptor_definition_path));
    errorId = 'MATLABGyroid:M04Gate0NotFrozen';
    if ~isfield(definition, 'source_of_record') || ...
            ~isstruct(definition.source_of_record) || ...
            ~isfield(definition.source_of_record, 'commit')
        throw(MException(errorId, ...
            'descriptor source-of-record commit is unavailable'));
    end
    sourceCommit = validate_text_scalar( ...
        definition.source_of_record.commit, 'source_of_record.commit', errorId);
    expectedSourceCommit = ...
        'a5f7d59b59f5c00e0f50c0bc3675f38f553454eb';
    if ~strcmp(sourceCommit, expectedSourceCommit)
        throw(MException(errorId, ...
            'descriptor source-of-record commit does not match M04'));
    end
    contract = struct( ...
        'workbook_sha256', ...
        'b4544b09c2688af8bc7aeeca5140a5d4c1cfc1c5b262709c9618c030d90fa561', ...
        'selection_sha256', ...
        'b953901b85178d5a54f9009e14b39af227b39e81e921aed52767c36585abe6c1', ...
        'compiler_version', compiler_version(), ...
        'descriptor_definition_sha256', config.descriptor_definition_sha256, ...
        'legacy_profile_sha256', ...
        config.descriptor_profile_sha256.legacy_small, ...
        'tpms_designer_commit', sourceCommit, ...
        'candidate_densities', [20, 24, 30, 32, 40, 48, 60, 64, 80, 96], ...
        'median_threshold', .02, 'p95_threshold', .05, ...
        'absolute_tolerance', 1e-12, ...
        'discovery_identity_sha256', ...
        '9718ad01a4bc0eb53b2b8ebb0ccdb9c8a36859404d80f08372d53df5462114e3', ...
        'confirmation_identity_sha256', ...
        'f71b6fff690af76716740d6a2e6eff2478e5319e2be6f1047d437e314c184a2b');
end
