        function testThresholdProfileHitsAllKnotsExactly(testCase)
            projected = project_method_constraints('M1', ...
                struct('c0', 0.04, 'c1', 0.10, 'c2', 0.20, 'w', 0), ...
                testCase.Config);

            testCase.verifyEqual( ...
                evaluate_threshold_profile([0, 1, 2], projected), ...
                [0.04, 0.10, 0.20], 'AbsTol', 10 * eps);
            testCase.verifyEqual( ...
                evaluate_threshold_profile([0; 1; 2], projected), ...
                [0.04; 0.10; 0.20], 'AbsTol', 10 * eps);
        end

        function testThresholdProfileUsesBothLinearSegments(testCase)
            projected = project_method_constraints('M3', ...
                struct('c0', 0.04, 'c1', 0.10, 'c2', 0.20, 'w', 4), ...
                testCase.Config);
            zOverL = [0.5, 1 - 1e-9, 1, 1 + 1e-9, 1.5];
            expected = [0.07, 0.10 - 0.06e-9, 0.10, ...
                0.10 + 0.10e-9, 0.15];

            testCase.verifyEqual( ...
                evaluate_threshold_profile(zOverL, projected), expected, ...
                'AbsTol', 100 * eps);
        end

        function testM2ThresholdIsProjectedConstant(testCase)
            projected = project_method_constraints('M2', ...
                struct('c0', 0.04, 'c1', 0.10, 'c2', 0.16, 'w', 4), ...
                testCase.Config);

            testCase.verifyEqual( ...
                evaluate_threshold_profile([0, 0.5, 1, 2], projected), ...
                0.10 * ones(1, 4), 'AbsTol', 10 * eps);
