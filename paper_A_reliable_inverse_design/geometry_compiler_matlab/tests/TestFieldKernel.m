        function testValidMethodFieldsProduceMixedSheetVolumes(testCase)
            cases = { ...
                'M1', [0.04, 0.10, 0.16, 0]; ...
                'M2', [0.04, 0.10, 0.16, 4]; ...
                'M3', [0.04, 0.10, 0.16, 4]};
            for caseIndex = 1:size(cases, 1)
                projected = TestFieldKernel.projectExample( ...
                    testCase, cases{caseIndex, 1}, cases{caseIndex, 2});
                field = build_graded_gyroid_field( ...
                    projected, testCase.Config, 16);
                volume = build_solid_volume(field, testCase.Config);

                expected = abs(field.G) <= reshape( ...
                    field.threshold, 1, 1, []);
                testCase.verifyClass(volume.solid, 'logical');
                testCase.verifySize(volume.solid, size(field.G));
                testCase.verifyEqual(volume.solid, expected);
                testCase.verifyGreaterThan(volume.solid_fraction, 0);
                testCase.verifyLessThan(volume.solid_fraction, 1);
                testCase.verifyEqual(volume.solid_count, nnz(expected));
                testCase.verifyEqual(volume.void_count, ...
                    numel(expected) - nnz(expected));
                testCase.verifyEqual(volume.voxel_count, numel(expected));
                testCase.verifyEqual(volume.convention, 'sheet_band');
            end
        end

        function testEmptyAndFullSheetVolumesRejected(testCase)
            emptyField = struct('G', ones(2, 2, 2), ...
                'threshold', [0, 0]);
            TestFieldKernel.verifyFailure(testCase, ...
                @() build_solid_volume(emptyField, testCase.Config), ...
                'MATLABGyroid:EmptySolid', 'sheet-band volume contains no solid voxels');

            fullField = struct('G', zeros(2, 2, 2), ...
                'threshold', [0.1, 0.1]);
            TestFieldKernel.verifyFailure(testCase, ...
                @() build_solid_volume(fullField, testCase.Config), ...
                'MATLABGyroid:FullSolid', 'sheet-band volume contains no void voxels');
        end

        function testInvalidSolidInputsRejected(testCase)
            validField = struct('G', ones(2, 2, 2), ...
                'threshold', [0.1, 0.1]);

            badConvention = testCase.Config;
            badConvention.solid_convention = 'signed_level_set';
            TestFieldKernel.verifyFailure(testCase, ...
                @() build_solid_volume(validField, badConvention), ...
                'MATLABGyroid:InvalidGeometry', ...
                'solid_convention must be "sheet_band"');

            nonFiniteField = validField;
            nonFiniteField.G(1) = NaN;
            TestFieldKernel.verifyFailure(testCase, ...
                @() build_solid_volume(nonFiniteField, testCase.Config), ...
                'MATLABGyroid:InvalidGeometry', ...
                'field.G must be a non-empty finite real numeric array');

            wrongThresholdLength = validField;
            wrongThresholdLength.threshold = 0.1;
            TestFieldKernel.verifyFailure(testCase, ...
                @() build_solid_volume(wrongThresholdLength, testCase.Config), ...
                'MATLABGyroid:InvalidGeometry', ...
                'field.threshold length must equal size(field.G, 3)');

            negativeThreshold = validField;
            negativeThreshold.threshold = [-0.1, 0.1];
            TestFieldKernel.verifyFailure(testCase, ...
                @() build_solid_volume(negativeThreshold, testCase.Config), ...
                'MATLABGyroid:InvalidGeometry', ...
                'field.threshold must contain finite nonnegative values');
        end

        function testKernelProvenanceLabelsAreFrozen(testCase)
            contract = compiler_contract();
            testCase.verifyEqual(contract.thresholdProfile, ...
                'piecewise_linear_knots_z_over_l_0_1_2');
            testCase.verifyEqual(contract.cellSizeProfile, ...
                'gamma(z_over_l)=1.5+z_over_l/w');
            testCase.verifyEqual(contract.gyroidFieldVersion, ...
                'small-si-s6-s9-candidate-v1');
            testCase.verifyEqual(contract.solidConvention, 'sheet_band');
        end
